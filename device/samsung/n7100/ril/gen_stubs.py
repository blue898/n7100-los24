#!/usr/bin/env python3
"""Generate the default ("not supported") halves of the radio AIDL services.

Every IRadioX request must be answered, or the framework's request (and often a
whole state machine) stays pending forever. For each frozen interface this writes
gen/RadioXBase.h: a BnRadioX subclass whose every request answers
REQUEST_NOT_SUPPORTED with default-constructed results; the hand-written services
override the requests the Samsung RIL can serve.

usage: gen_stubs.py <aidl_api dir> <version> <out dir>
"""
import os
import re
import sys

PKGS = ["config", "modem", "sim", "network", "data", "voice", "messaging"]

# requests whose response isn't named <request>Response
RESPONSE_NAMES = {"hangup": "hangupConnectionResponse"}

PRIMS = {
    "int": "int32_t", "long": "int64_t", "boolean": "bool", "byte": "int8_t",
    "char": "char16_t", "float": "float", "double": "double", "String": "std::string",
}


def cpp_type(t):
    t = t.strip()
    if t.startswith("@nullable "):
        return "std::optional<%s>" % cpp_type(t[len("@nullable "):])
    if t.endswith("[]"):
        inner = t[:-2].strip()
        return "std::vector<uint8_t>" if inner == "byte" else "std::vector<%s>" % cpp_type(inner)
    if t.startswith("List<"):
        return "std::vector<%s>" % cpp_type(t[5:-1])
    if t in PRIMS:
        return PRIMS[t]
    if "." in t:
        name = "::aidl::" + t.replace(".", "::")
        if t.split(".")[-1].startswith("IRadio"):
            return "std::shared_ptr<%s>" % name
        return name
    raise ValueError("unknown type " + t)


API = None
VER = None


def is_enum(t):
    # android.hardware.radio.data.DataRequestReason -> .../android.hardware.radio.data/<ver>/...
    parts = t.split(".")
    pkg = ".".join(parts[:-1])
    path = os.path.join(API, pkg, VER, *parts[:-1], parts[-1] + ".aidl")
    if not os.path.exists(path):
        return False
    return re.search(r"^enum ", open(path).read(), re.M) is not None


def is_by_value(t):
    t = t.strip()
    if t.startswith("@nullable "):
        return False
    if t in PRIMS:
        return t != "String"
    return "." in t and not t.endswith("[]") and is_enum(t)


METHOD = re.compile(r"^\s*oneway void (\w+)\((.*)\);\s*$")


def methods(path):
    out = []
    for line in open(path):
        m = METHOD.match(line)
        if not m:
            continue
        params = []
        for p in filter(None, [s.strip() for s in m.group(2).split(",")]) if m.group(2).strip() else []:
            nullable = "@nullable" in p
            p = re.sub(r"@\w+\s*", "", p)
            words = p.split()
            if words[0] in ("in", "out", "inout"):
                words = words[1:]
            t = " ".join(words[:-1])
            params.append(("@nullable " + t if nullable else t, words[-1]))
        out.append((m.group(1), params))
    return out


def gen(api, ver, pkg, outdir):
    Pkg = pkg[0].upper() + pkg[1:]
    base = os.path.join(api, "android.hardware.radio." + pkg, ver, "android", "hardware", "radio", pkg)
    reqs = methods(os.path.join(base, "IRadio%s.aidl" % Pkg))
    resps = {n: p for n, p in methods(os.path.join(base, "IRadio%sResponse.aidl" % Pkg))}
    ns = "::aidl::android::hardware::radio::" + pkg
    L = []
    L.append("// Generated by gen_stubs.py from android.hardware.radio.%s V%s. Do not edit." % (pkg, ver))
    L.append("#pragma once\n")
    L.append("#include <aidl/android/hardware/radio/%s/BnRadio%s.h>" % (pkg, Pkg))
    L.append('#include "RadioUtil.h"\n')
    L.append("namespace android::hardware::radio::n7100 {\n")
    L.append("class Radio%sBase : public %s::BnRadio%s {" % (Pkg, ns, Pkg))
    L.append("  protected:")
    L.append("    std::shared_ptr<%s::IRadio%sResponse> mResp;" % (ns, Pkg))
    L.append("    std::shared_ptr<%s::IRadio%sIndication> mInd;\n" % (ns, Pkg))
    L.append("  public:")
    L.append("    std::shared_ptr<%s::IRadio%sResponse> resp() { return mResp; }" % (ns, Pkg))
    L.append("    std::shared_ptr<%s::IRadio%sIndication> ind() { return mInd; }\n" % (ns, Pkg))
    for name, params in reqs:
        sig = ", ".join("%s in_%s" % (cpp_type(t) if is_by_value(t) else "const %s&" % cpp_type(t), n)
                        for t, n in params)
        if name == "setResponseFunctions":
            L.append("    ndk::ScopedAStatus setResponseFunctions(%s) override {" % sig)
            L.append("        mResp = in_%s;" % params[0][1])
            L.append("        mInd = in_%s;" % params[1][1])
            L.append("        onResponseFunctionsSet();")
            L.append("        return ndk::ScopedAStatus::ok();")
            L.append("    }")
            continue
        if name == "responseAcknowledgement":
            L.append("    ndk::ScopedAStatus responseAcknowledgement() override { return ndk::ScopedAStatus::ok(); }")
            continue
        rname = RESPONSE_NAMES.get(name, name + "Response")
        if rname not in resps:
            raise ValueError("%s: no %s" % (pkg, rname))
        rargs = ["notSupported(in_serial)"] + ["{}"] * (len(resps[rname]) - 1)
        L.append("    ndk::ScopedAStatus %s(%s) override {" % (name, sig))
        L.append('        logUnsupported("%s.%s");' % (pkg, name))
        L.append("        if (mResp) mResp->%s(%s);" % (rname, ", ".join(rargs)))
        L.append("        return ndk::ScopedAStatus::ok();")
        L.append("    }")
    L.append("\n    virtual void onResponseFunctionsSet() {}")
    L.append("};\n")
    L.append("}  // namespace android::hardware::radio::n7100")
    with open(os.path.join(outdir, "Radio%sBase.h" % Pkg), "w") as f:
        f.write("\n".join(L) + "\n")
    return len(reqs)


def main():
    global API, VER
    api, ver, outdir = sys.argv[1:4]
    API, VER = api, ver
    os.makedirs(outdir, exist_ok=True)
    for p in PKGS:
        print("%s: %d requests" % (p, gen(api, ver, p, outdir)))


if __name__ == "__main__":
    main()
